def screen_keys(code, reason, detail):
    if code == "CONFIG_RELOAD_FAILED":
        return ["dbconf.reloadFailed." + (reason if reason in ("restored", "restored_unit_reload_failed", "restored_running_unknown") else "notRestored"),
                "dbconf.reloadSaid"]
    if code == "CURRENT_SETTINGS_UNREADABLE" and reason == "scheduled_tasks":
        return (["cron.unknown." + detail] if detail else ["cron.unknown"]) + ["cron.unknown.said"]
    if code == "MAIL_QUEUE_UNREADABLE":
        return ["postfix.queue.unreadable" + ("." + reason if reason else ""), "postfix.queue.said"]
    if code == "MAIL_POLICY_NOT_RELOADED":
        return ["err.MAIL_POLICY_NOT_RELOADED" + ("." + reason if reason else ""), "mailpolicy.postfixSaid"]
    return None


def corrected(answer, texts, values):
    detail = answer.get("detail")
    if not detail and answer.get("code") == "CURRENT_SETTINGS_UNREADABLE" and "/etc/cron.allow" in str(answer.get("error")):
        detail = "cron_allow"     # the settings driver did not keep the answer's `detail` token; its sentence names the cause
    keys = screen_keys(answer.get("code"), answer.get("reason"), detail)
    if not keys or CATALOG is None:
        return texts
    out = {}
    for key in keys:
        if key in CATALOG["en"]:
            out[key] = {}
            for language in ("en", "tr"):
                text = CATALOG[language].get(key, key)
                for name, value in values.items():
                    text = text.replace("{" + name + "}", str(value))
                out[key][language] = text
    return out


seen = {}
for name, directory, result in runs():
    for _, section in sections(directory):
        for call in section["calls"]:
            answer = call.get("answer")
            if not answer or not (answer.get("code") or answer.get("error")):
                continue
            key = (call.get("status"), answer.get("code"), answer.get("reason"), answer.get("error"))
            entry = seen.setdefault(key, {"where": [], "vars": [], "texts": {}, "detail": set()})
            if len(entry["where"]) < 6:
                entry["where"].append(f"{name} {section['section']}: {call['label']}")
            if answer.get("vars") and len(entry["vars"]) < 3 and answer["vars"] not in entry["vars"]:
                entry["vars"].append(answer["vars"])
            if answer.get("detail"):
                entry["detail"].add(str(answer["detail"]))
            values = dict(answer.get("vars") or {})
            values.setdefault("service", "PostgreSQL" if "postgresql" in str(values.get("unit", "")) else values.get("unit", ""))
            for k, v in corrected(answer, call.get("catalogue_texts") or {}, values).items():
                entry["texts"].setdefault(k, v)
for (status, code, reason, error), entry in sorted(seen.items(), key=lambda item: (str(item[0][1]), str(item[0][2]), str(item[0][0]))):
    texts.append(f"## `{status} {code or '(no code)'}`" + (f" / `{reason}`" if reason else ""))
    texts.append("")
    texts.append(f"- API: \"{error}\"")
    if entry["detail"]:
        texts.append(f"- `detail` (cause token): {', '.join(sorted(entry['detail']))}")
    for item in entry["vars"]:
        texts.append(f"- vars: `{one_line(item, 700)}`")
    for key, value in entry["texts"].items():
        texts.append(f"- `{key}`")
        texts.append(f"  - EN: \"{value.get('en')}\"")
        texts.append(f"  - TR: \"{value.get('tr')}\"")
    texts.append(f"- seen in: {'; '.join(entry['where'])}")
    texts.append("")
open(os.path.join(E, "texts-en-tr.md"), "w", encoding="utf-8", newline="\n").write("\n".join(texts) + "\n")

