"""set2: tables and extracts generated from the staged evidence (read-only over the cells' JSON files).

usage: summary.py EVIDENCE_DIR  -> sections-table.md, checks-not-passed.txt, texts-en-tr.md, group-b-service-actions.md,
       group-c-request-identity.md, native-facts.json in EVIDENCE_DIR
"""
import glob
import json
import os
import sys

E = sys.argv[1]
STANDARD = {"section", "title", "node", "native_evidence", "started_at", "finished_at", "calls", "checks", "natives", "notes",
            "owner_actions", "verdict", "substeps"}


def load(path):
    with open(path, encoding="utf-8") as stream:
        return json.load(stream)


def runs():
    found = []
    for result in sorted(glob.glob(os.path.join(E, "*", "run-*", "result.json"))):
        directory = os.path.dirname(result)
        found.append((os.path.relpath(directory, E).replace("\\", "/"), directory, load(result)))
    return found


def sections(directory):
    out = []
    for path in sorted(glob.glob(os.path.join(directory, "steps", "*", "section.json"))):
        out.append((os.path.basename(os.path.dirname(path)), load(path)))
    return out


def seconds(a, b):
    import datetime as dt
    try:
        f = "%Y-%m-%dT%H:%M:%SZ"
        return int((dt.datetime.strptime(b, f) - dt.datetime.strptime(a, f)).total_seconds())
    except (TypeError, ValueError):
        return None


def one_line(value, limit=400):
    text = json.dumps(value, ensure_ascii=False, sort_keys=True)
    return text if len(text) <= limit else text[:limit] + " ..."


# -- sections-table.md and checks-not-passed.txt ---------------------------------------------------------------------
table, notpassed = ["# set2: steps and sections per run (generated by tools/summary.py)", ""], []
for name, directory, result in runs():
    table += [f"### {name}: overall `{result['overall']}`, node {result['identity']['node']}, cell kind `{result['cell_kind']}`, "
              f"`native_evidence: {str(result['native_evidence']).lower()}`", "",
              "| Step | Verdict | Started (UTC) | Finished (UTC) | Seconds |", "| --- | --- | --- | --- | --- |"]
    for step in result["steps"]:
        table.append(f"| {step['name']} | {step['verdict']} | {step.get('started_at')} | {step.get('finished_at')} | "
                     f"{seconds(step.get('started_at'), step.get('finished_at'))} |")
    table += ["", "| Section | Verdict | Sub-steps | Checks | Not passed |", "| --- | --- | --- | --- | --- |"]
    for _, section in sections(directory):
        checks = section["checks"]
        bad = [c for c in checks if c["ok"] is not True]
        subs = ", ".join(f"{k} {v}" for k, v in (section.get("substeps") or {}).items())
        table.append(f"| {section['section']} | **{section['verdict']}** | {subs[:700]} | {len(checks)} | {len(bad) or '-'} |")
        if section.get("error"):
            notpassed.append(f"{name} {section['section']} ERROR: {section['error'][:1500]}")
        for check in bad:
            notpassed.append(f"{name} {section['section']} {'FAIL' if check['ok'] is False else 'NOT ESTABLISHED'}: {check['name']}")
            notpassed.append("    " + one_line(check["detail"], 1800))
        for note in section.get("notes", []):
            notpassed.append(f"{name} {section['section']} note: {note['note']}")
            notpassed.append("    " + one_line(note.get("detail"), 900))
    table.append("")
open(os.path.join(E, "sections-table.md"), "w", encoding="utf-8", newline="\n").write("\n".join(table) + "\n")
open(os.path.join(E, "checks-not-passed.txt"), "w", encoding="utf-8", newline="\n").write("\n".join(notpassed) + "\n")

