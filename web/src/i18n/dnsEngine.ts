export function dnsEngineText(
    locale: 'en' | 'tr',
    key: DNSEngineCopyKey,
    vars?: Record<string, string | number>,
): string {
    const catalog: Record<DNSEngineCopyKey, string> = locale === 'tr' ? dnsEngineTr : dnsEngineEn;
    let text = catalog[key];
    if (vars) {
        for (const [name, value] of Object.entries(vars)) {
            text = text.split(`{${name}}`).join(String(value));
        }
    }
    return text;
}
